import logging
import os
import time
from pathlib import Path
from typing import Dict, Any, Optional
from google import genai
from google.genai import types
from dotenv import load_dotenv

from app.config import load_config
from app.prompts import SYSTEM_PROMPT
from app.storage import save_chat_turn, export_hike_dossier
from app.tools import (
    read_safety_guidelines,
    get_mountain_weather,
    get_mountain_routes,
)
from app.cartographer import CartographerAgent
from app.schema import AgentCard

BASE_DIR = Path(__file__).resolve().parent.parent
load_dotenv(dotenv_path=BASE_DIR / ".env")

logger = logging.getLogger("MountainAgent")


class MountainAgent:
    def __init__(self):
        self.config = load_config()
        api_key = os.getenv("GOOGLE_API_KEY")
        if not api_key:
            raise ValueError(
                "GOOGLE_API_KEY is not set in the .env file. "
                "Please add your Google Gemini API key to run the agent."
            )

        self.client = genai.Client(api_key=api_key)

        self.tools = [
            read_safety_guidelines,
            get_mountain_weather,
            get_mountain_routes,
        ]

        # Multi-user session storage: maps session_id -> chat session
        self.sessions: Dict[str, Any] = {}
        # Stores the latest agent response per session for quick dossier export
        self.last_responses: Dict[str, str] = {}
        # Maps session_id -> latest map spec generated by CartographerAgent
        self.last_maps: Dict[str, Optional[Dict[str, Any]]] = {}
        # Multi-user token tracking: maps session_id -> cumulative/turn tokens
        self.session_tokens: Dict[str, Dict[str, int]] = {}
        self.last_turn_tokens: Dict[str, Dict[str, int]] = {}

        # Agent 2: Mountain Cartographer Agent (GIS & Interactive Mapping Specialist)
        self.cartographer = CartographerAgent(client=self.client, model=self.config.model)

        # Standardized Agent Card descriptor
        self.agent_card = AgentCard(
            agent_id="mountain-guide-agent",
            name="RoMountainGuide",
            version="2.0.0",
            role="Lead Alpine Expedition Guide & Safety Expert",
            description="Analyzes Romanian Carpathian routes, checks live high-altitude weather and Salvamont safety guidelines, and generates structured trail dossiers.",
            capabilities=[
                "carpathian_route_recommendation",
                "real_time_open_meteo_weather",
                "open_street_map_overpass_query",
                "salvamont_safety_advisory",
                "multilingual_mirroring",
                "a2a_cartographer_orchestration",
            ],
            inputs={
                "message": "User query in any supported language (Romanian, English, Spanish, etc.)",
                "session_id": "Unique user session identifier for conversational continuity",
            },
            outputs={
                "response": "6-section Mountain Trail Dossier formatted in Markdown",
                "map_data": "Optional structured map specification produced by CartographerAgent",
            },
        )

    def _create_chat_session(self, model_name: str):
        return self.client.chats.create(
            model=model_name,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                tools=self.tools,
                temperature=0.2,
            ),
        )

    def _get_or_create_chat(self, session_id: str):
        """Retrieves or initializes a chat session for a specific user."""
        if session_id not in self.sessions:
            self.sessions[session_id] = self._create_chat_session(self.config.model)
        return self.sessions[session_id]

    def send_message(
        self,
        message: str,
        session_id: str = "default",
        user_name: Optional[str] = None,
    ) -> str:
        """
        Sends a message to the agent within the user's isolated session.
        Includes automatic retry and fallback if a model experiences high demand (503).
        Automatically saves the turn to local history.
        """
        response_text = ""
        last_response_obj = None
        max_retries = 2
        fallback_models = [self.config.model, "gemini-3.5-flash-lite", "gemini-flash-latest"]
        # Remove duplicates while preserving order
        unique_models = list(dict.fromkeys(fallback_models))

        for model in unique_models:
            for attempt in range(max_retries):
                try:
                    if session_id not in self.sessions or self.sessions[session_id]._model != model:
                        self.sessions[session_id] = self._create_chat_session(model)

                    chat = self.sessions[session_id]
                    response = chat.send_message(message)
                    response_text = response.text or ""
                    last_response_obj = response
                    if response_text:
                        break
                except Exception as e:
                    err_str = str(e)
                    logger.warning(f"Attempt {attempt + 1} with model {model} failed: {err_str[:120]}")
                    if "503" in err_str or "UNAVAILABLE" in err_str or "404" in err_str:
                        time.sleep(1.5)
                        continue
                    else:
                        break
            if response_text:
                break

        if not response_text:
            response_text = (
                "[WARNING] A temporary issue occurred while contacting the Gemini servers. "
                "Please retry in a few moments."
            )

        # Extract token usage metadata from Gemini response
        turn_prompt = 0
        turn_candidates = 0
        turn_total = 0
        if last_response_obj and hasattr(last_response_obj, "usage_metadata") and last_response_obj.usage_metadata:
            turn_prompt = getattr(last_response_obj.usage_metadata, "prompt_token_count", 0) or 0
            turn_candidates = getattr(last_response_obj.usage_metadata, "candidates_token_count", 0) or 0
            turn_total = getattr(last_response_obj.usage_metadata, "total_token_count", 0) or (turn_prompt + turn_candidates)

        if session_id not in self.session_tokens:
            self.session_tokens[session_id] = {
                "prompt_tokens": 0,
                "candidates_tokens": 0,
                "total_tokens": 0,
                "turns_count": 0,
            }

        self.session_tokens[session_id]["prompt_tokens"] += turn_prompt
        self.session_tokens[session_id]["candidates_tokens"] += turn_candidates
        self.session_tokens[session_id]["total_tokens"] += turn_total
        self.session_tokens[session_id]["turns_count"] += 1

        self.last_turn_tokens[session_id] = {
            "turn_prompt": turn_prompt,
            "turn_candidates": turn_candidates,
            "turn_total": turn_total,
            "session_total": self.session_tokens[session_id]["total_tokens"],
        }

        # Capture previous turn response for multi-turn pronoun and map resolution
        previous_response = self.last_responses.get(session_id)

        # Store latest response for this user
        self.last_responses[session_id] = response_text

        # A2A: Delegate to Cartographer Agent to generate route map specification
        try:
            map_spec = self.cartographer.generate_map_spec(
                route_text=response_text,
                user_context=message,
                history_text=previous_response,
            )
            if map_spec:
                self.last_maps[session_id] = map_spec
            elif previous_response and any(k in message.lower() for k in ["harta", "map", "acest traseu", "this route"]):
                # Retain existing map if user specifically asked about the current route
                pass
            else:
                self.last_maps[session_id] = None
        except Exception as e:
            logger.warning(f"Cartographer agent generation failed: {e}")
            self.last_maps[session_id] = None

        # Auto-save conversation to local storage with token metadata
        save_chat_turn(
            session_id=session_id,
            user_message=message,
            assistant_message=response_text,
            user_name=user_name,
            metadata={"tokens": self.last_turn_tokens.get(session_id, {})},
        )

        return response_text

    def export_last_hike(
        self,
        session_id: str = "default",
        custom_title: Optional[str] = None,
        user_name: Optional[str] = None,
    ) -> Optional[Path]:
        """
        Exports the latest recommendation for the given user session into a Markdown dossier.
        """
        last_text = self.last_responses.get(session_id)
        if not last_text:
            return None

        # Extract title from text if not provided
        title = custom_title
        if not title:
            # Try to grab title from markdown headers like "### Trail Dossier: ...", "### Dosar Traseu: ..."
            for line in last_text.splitlines():
                clean_line = line.strip()
                if any(k in clean_line.lower() for k in ["trail dossier:", "dosar traseu:", "dossier:", "traseu:", "trail:", "ruta:"]):
                    title = clean_line.split(":", 1)[-1].strip()
                    break
                elif clean_line.startswith("### ") and len(clean_line) > 5:
                    title = clean_line.lstrip("#").strip()
                    break
        if not title:
            title = "Carpathian_Mountain_Trail"

        return export_hike_dossier(
            title=title,
            content=last_text,
            user_name=user_name,
        )

    def get_last_map(self, session_id: str = "default") -> Optional[Dict[str, Any]]:
        """
        Retrieves the latest interactive map specification generated by CartographerAgent.
        """
        return self.last_maps.get(session_id)

    def get_last_turn_tokens(self, session_id: str = "default") -> Dict[str, int]:
        """
        Returns the token usage breakdown for the latest turn in this session.
        """
        return self.last_turn_tokens.get(session_id, {
            "turn_prompt": 0,
            "turn_candidates": 0,
            "turn_total": 0,
            "session_total": 0,
        })

    def get_session_tokens(self, session_id: str = "default") -> Dict[str, int]:
        """
        Returns cumulative token statistics for the entire session.
        """
        return self.session_tokens.get(session_id, {
            "prompt_tokens": 0,
            "candidates_tokens": 0,
            "total_tokens": 0,
            "turns_count": 0,
        })

    def reset_session(self, session_id: str) -> None:
        """Clears memory for a specific user session."""
        if session_id in self.sessions:
            del self.sessions[session_id]
        if session_id in self.last_responses:
            del self.last_responses[session_id]
        if session_id in self.last_maps:
            del self.last_maps[session_id]
        if session_id in self.session_tokens:
            del self.session_tokens[session_id]
        if session_id in self.last_turn_tokens:
            del self.last_turn_tokens[session_id]