import json
import os
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
SAVED_HIKES_DIR = PROJECT_ROOT / "saved_hikes"

DATA_DIR.mkdir(parents=True, exist_ok=True)
SAVED_HIKES_DIR.mkdir(parents=True, exist_ok=True)

CHAT_HISTORY_FILE = DATA_DIR / "chat_history.json"


def save_chat_turn(
    session_id: str,
    user_message: str,
    assistant_message: str,
    user_name: Optional[str] = None,
    metadata: Optional[Dict[str, Any]] = None,
) -> None:
    """
    Saves a conversation turn into the local JSON history file.
    Each user/session has an isolated record.
    """
    history = load_all_history()

    if session_id not in history:
        history[session_id] = {
            "session_id": session_id,
            "user_name": user_name or "Anonymous Hiker",
            "created_at": datetime.now().isoformat(),
            "messages": [],
        }

    turn = {
        "timestamp": datetime.now().isoformat(),
        "user_message": user_message,
        "assistant_message": assistant_message,
        "metadata": metadata or {},
    }

    history[session_id]["messages"].append(turn)

    with open(CHAT_HISTORY_FILE, "w", encoding="utf-8") as f:
        json.dump(history, f, ensure_ascii=False, indent=2)


def load_all_history() -> Dict[str, Any]:
    """Loads all chat history from JSON storage."""
    if not CHAT_HISTORY_FILE.exists():
        return {}
    try:
        with open(CHAT_HISTORY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return {}


def get_user_history(session_id: str) -> List[Dict[str, Any]]:
    """Gets the message turns for a specific user session."""
    history = load_all_history()
    user_data = history.get(str(session_id), {})
    return user_data.get("messages", [])


def _to_ascii_filename(text: str) -> str:
    """
    Transliterates Romanian and other special characters to standard ASCII
    to prevent filesystem issues and HTTP Latin-1 header errors.
    """
    transliterations = {
        "ș": "s", "Ș": "S",
        "ț": "t", "Ț": "T",
        "ă": "a", "Ă": "A",
        "î": "i", "Î": "I",
        "â": "a", "Â": "A",
    }
    for char, rep in transliterations.items():
        text = text.replace(char, rep)

    clean = re.sub(r'[^a-zA-Z0-9_\-\.]', '_', text)
    clean = re.sub(r'_+', '_', clean).strip('_')
    return clean or "Mountain_Trail_Guide"


def export_hike_dossier(
    title: str,
    content: str,
    massif: Optional[str] = None,
    difficulty: Optional[str] = None,
    user_name: Optional[str] = None,
) -> Path:
    """
    Exports a structured hiking dossier into a standalone Markdown file.
    This file is ready to be transferred to phones or printed for offline trail use.

    Returns the Path to the created markdown file.
    """
    # Sanitize title to safe ASCII for cross-platform filesystems and HTTP headers
    clean_title = _to_ascii_filename(title)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{clean_title}_{timestamp}.md"
    file_path = SAVED_HIKES_DIR / filename

    dossier_content = f"""# Mountain Trail Guide: {title}

**Generated by:** RoMountainAgent - Your Intelligent Mountain Guide
**Generated on:** {datetime.now().strftime("%B %d, %Y, %H:%M")}
**User:** {user_name or "Hiker"}
{f"**Massif:** {massif}" if massif else ""}
{f"**Difficulty:** {difficulty}" if difficulty else ""}

---

{content.strip()}

---

## Mountain Emergency Contacts (Salvamont)
- **Salvamont National Dispatch:** 0-SALVAMONT (+40 725 826 668)
- **European Emergency Number:** 112
- *Recommendation: Download the Salvamont Romania mobile app for emergency GPS location sharing.*
"""

    with open(file_path, "w", encoding="utf-8") as f:
        f.write(dossier_content)

    return file_path


def list_saved_hikes() -> List[Dict[str, Any]]:
    """Lists all exported hike markdown dossiers available on the system."""
    hikes = []
    for file in sorted(SAVED_HIKES_DIR.glob("*.md"), key=os.path.getmtime, reverse=True):
        stat = file.stat()
        hikes.append({
            "filename": file.name,
            "path": str(file),
            "size_bytes": stat.st_size,
            "created_at": datetime.fromtimestamp(stat.st_mtime).strftime("%Y-%m-%d %H:%M"),
        })
    return hikes
