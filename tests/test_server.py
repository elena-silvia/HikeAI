def test_map_endpoint_flow(client):
    session_id = "test_map_web"
    headers = {"X-Access-Passcode": "carpathians2026"}

    # Initially no map
    res_404 = client.get(f"/api/map?session_id={session_id}", headers=headers)
    assert res_404.status_code == 404

    # Inject mock map generated by Cartographer
    agent.last_maps[session_id] = {
        "trail_name": "Bucegi - Omu Peak",
        "massif": "Bucegi Mountains",
        "center": {"lat": 45.4456, "lon": 25.4578},
        "zoom": 13,
        "waypoints": [{"name": "Omu Peak", "lat": 45.4456, "lon": 25.4578, "type": "summit"}],
        "polyline": [[45.4180, 25.5330], [45.4456, 25.4578]],
    }

    res_200 = client.get(f"/api/map?session_id={session_id}", headers=headers)
    assert res_200.status_code == 200
    data = res_200.json()
    assert data["trail_name"] == "Bucegi - Omu Peak"
    assert len(data["waypoints"]) == 1


